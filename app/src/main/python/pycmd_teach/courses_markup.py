"""Courses for the file formats: markup, styling, configuration and data.

None of these is a program, so none of them prints anything, and the lessons
here are built from the shape of the file rather than from its output. That
makes them shorter courses - which is honest. There is less to know about TOML
than about Rust, and padding it out would only waste somebody's evening.

Regular expressions are in here too, as a course of their own. They are not a
file format and PyCmd has no `.regex` extension, but they turn up in every
language in this app and nobody is taught them anywhere.
"""

