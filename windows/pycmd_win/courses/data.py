"""R, AWK and Prolog - languages for data and for logic."""

from pycmd_teach import Course, T, U

R = Course(
    "r", "R", "The statistician's language. Vectors first. Runs with Rscript.",
    ".R", "text",
    [
        U("First steps", "Everything is a vector."),
        T("print", "Shows a value. `[1]` means: this line starts at element one.",
          "print(42)", "[1] 42"),
        T("cat", "Prints without the index, and without a newline unless asked.",
          'cat("hello\\n")', "hello"),
        T("Assignment", "`<-` is R's arrow. `=` works too.",
          "n <- 5\nprint(n * n)", "[1] 25"),
        T("Arithmetic", "`/` keeps the fraction.",
          "print(7 / 2)", "[1] 3.5"),
        T("Integer division", "`%/%` and `%%`.",
          "cat(7 %/% 2, 7 %% 2, \"\\n\")", "3 1"),
        T("Powers", "`^` raises to a power.",
          "print(2 ^ 10)", "[1] 1024"),
        T("paste", "Joins with a space.",
          'print(paste("py", "cmd"))', '[1] "py cmd"'),
        T("paste0", "Joins with nothing.",
          'cat(paste0("py", "cmd"), "\\n")', "pycmd"),
        T("Comments", "`#` to the end of the line.",
          '# a note\ncat("ok\\n")', "ok"),

        U("Vectors"),
        T("c()", "Combines values into a vector.",
          "print(c(1, 2, 3))", "[1] 1 2 3"),
        T("Ranges", "`1:5` counts from one to five.",
          "print(1:5)", "[1] 1 2 3 4 5"),
        T("Arithmetic on vectors", "Applied to every element at once.",
          "print(c(1, 2, 3) * 10)", "[1] 10 20 30"),
        T("Indexing from one", "The first element is 1, not 0.",
          "x <- c(10, 20, 30)\nprint(x[1])", "[1] 10"),
        T("Negative indexes drop", "`x[-1]` is everything but the first.",
          "x <- c(10, 20, 30)\nprint(x[-1])", "[1] 20 30"),
        T("length", "How many elements.",
          "print(length(c(4, 5, 6)))", "[1] 3"),
        T("sum and mean", "Summaries of a whole vector.",
          "x <- c(2, 4, 6)\ncat(sum(x), mean(x), \"\\n\")", "12 4"),
        T("Logical indexing", "A vector of TRUE/FALSE picks elements.",
          "x <- 1:10\nprint(x[x %% 2 == 0])", "[1]  2  4  6  8 10"),
        T("seq", "Steps of your choosing.",
          "print(seq(0, 20, by = 5))", "[1]  0  5 10 15 20"),
        T("rep", "Repeats a value as many times as asked.",
          'print(rep("a", 3))', '[1] "a" "a" "a"'),
        T("rev and sort", "Reverse and sort.",
          "print(sort(c(3, 1, 2)))", "[1] 1 2 3"),
        T("Named vectors", "Elements can carry names.",
          "ages <- c(ada = 36, bob = 5)\nprint(ages[[\"ada\"]])", "[1] 36"),
        T("which", "The positions where a test is true.",
          "print(which(c(5, 8, 2, 9) > 6))", "[1] 2 4"),
        T("NA", "A missing value. Summaries need na.rm.",
          "x <- c(1, NA, 3)\nprint(sum(x, na.rm = TRUE))", "[1] 4"),

        U("Decisions and functions"),
        T("if", "As you would expect.",
          'n <- 4\nif (n %% 2 == 0) cat("even\\n") else cat("odd\\n")', "even"),
        T("ifelse", "A vectorised if: one answer per element.",
          'print(ifelse(c(1, 6) > 3, "big", "small"))', '[1] "small" "big"  '),
        T("for", "Loops over a vector.",
          "for (i in 1:3) cat(i)\ncat(\"\\n\")", "123"),
        T("while", "Loops while the test holds.",
          "n <- 3\nwhile (n > 0) {\n  cat(n)\n  n <- n - 1\n}\ncat(\"\\n\")", "321"),
        T("Functions", "`function(x) ...`, assigned to a name.",
          "square <- function(x) x * x\nprint(square(9))", "[1] 81"),
        T("Default arguments", "Used when left out.",
          'hi <- function(who = "you") paste("hi", who)\ncat(hi(), "\\n")', "hi you"),
        T("The last value is returned", "No `return` needed.",
          "f <- function(x) {\n  y <- x * 2\n  y + 1\n}\nprint(f(5))", "[1] 11"),
        T("sapply", "Applies a function to every element.",
          "print(sapply(1:4, function(x) x ^ 2))", "[1]  1  4  9 16"),
        T("The native pipe", "`|>` passes the left side as the first argument.",
          "c(1, 4, 9) |> sqrt() |> sum() |> print()", "[1] 6"),
        T("Recursion", "Functions can call themselves.",
          "fact <- function(n) if (n == 0) 1 else n * fact(n - 1)\nprint(fact(5))",
          "[1] 120"),

        U("Data structures"),
        T("Lists", "Mixed types, accessed with $.",
          'p <- list(name = "Ada", age = 36)\ncat(p$name, "\\n")', "Ada"),
        T("Matrices", "A vector with dimensions.",
          "m <- matrix(1:6, nrow = 2)\nprint(dim(m))", "[1] 2 3"),
        T("Matrix indexing", "`[row, column]`.",
          "m <- matrix(1:6, nrow = 2)\nprint(m[2, 3])", "[1] 6"),
        T("Data frames", "Tables: columns of equal length.",
          'df <- data.frame(n = c("a", "b"), v = c(1, 2))\nprint(nrow(df))', "[1] 2"),
        T("Columns with $", "Each column is a vector.",
          "df <- data.frame(v = c(3, 5, 7))\nprint(mean(df$v))", "[1] 5"),
        T("Filtering rows", "Logical indexing on rows.",
          "df <- data.frame(v = c(3, 5, 7))\nprint(df[df$v > 4, ])", "[1] 5 7"),
        T("table", "Counts each value.",
          'print(table(c("a", "b", "a"))[["a"]])', "[1] 2"),
        T("Factors", "Categories with a fixed set of levels.",
          'f <- factor(c("lo", "hi", "lo"))\nprint(levels(f))', '[1] "hi" "lo"'),

        U("Text"),
        T("nchar", "Characters in a string.",
          'print(nchar("pycmd"))', "[1] 5"),
        T("toupper", "Upper case.",
          'cat(toupper("pycmd"), "\\n")', "PYCMD"),
        T("substr", "From a start to an end, counting from one.",
          'cat(substr("pycmd", 3, 5), "\\n")', "cmd"),
        T("strsplit", "Returns a list; take the first element.",
          'print(strsplit("a,b,c", ",")[[1]])', '[1] "a" "b" "c"'),
        T("sprintf", "C-style formatting.",
          'cat(sprintf("%05.1f", 3.14159), "\\n")', "003.1"),
        T("gsub", "Replace every match of a pattern.",
          'cat(gsub("a", "o", "banana"), "\\n")', "bonono"),
        T("grepl", "Does it match?",
          'print(grepl("cm", c("pycmd", "py")))', "[1]  TRUE FALSE"),
    ],
)

AWK = Course(
    "awk", "AWK", "The text-processing language from 1977, still everywhere. Runs with gawk.",
    ".awk", "text",
    [
        U("First steps", "BEGIN runs before any input is read."),
        T("BEGIN and print", "`print` writes a line.",
          'BEGIN { print "hello" }', "hello"),
        T("Several values", "Commas put a space between them.",
          'BEGIN { print "a", "b", 3 }', "a b 3"),
        T("Joining", "Values side by side are concatenated.",
          'BEGIN { print "py" "cmd" }', "pycmd"),
        T("Variables", "No declaration; they start as empty or zero.",
          "BEGIN { n = 5; print n * n }", "25"),
        T("Arithmetic", "Numbers are floating point.",
          "BEGIN { print 7 / 2 }", "3.5"),
        T("int", "Drops the fraction.",
          "BEGIN { print int(7 / 2), 7 % 2 }", "3 1"),
        T("printf", "Formatting, as in C. No newline unless you say.",
          'BEGIN { printf "%05.1f\\n", 3.14159 }', "003.1"),
        T("Uninitialised is zero", "Adding to nothing starts from 0.",
          "BEGIN { total += 4; print total }", "4"),
        T("Comments", "`#` to the end of the line.",
          '# a note\nBEGIN { print "ok" }', "ok"),

        U("Decisions and loops"),
        T("if", "With braces for several statements.",
          'BEGIN {\n    n = 4\n    if (n % 2 == 0) print "even"\n    else print "odd"\n}',
          "even"),
        T("The ternary", "`test ? a : b`.",
          'BEGIN { n = 9; print (n > 5 ? "big" : "small") }', "big"),
        T("for", "C style: start, test, step.",
          'BEGIN {\n    for (i = 1; i <= 3; i++) printf "%d", i\n    print ""\n}', "123"),
        T("while", "Loops while the test holds.",
          'BEGIN {\n    n = 3\n    while (n > 0) printf "%d", n--\n    print ""\n}', "321"),
        T("Comparisons with strings", "Text compares alphabetically.",
          'BEGIN { print ("apple" < "banana") }', "1"),
        T("Regex matching", "`~` tests a string against a pattern.",
          'BEGIN { if ("pycmd" ~ /cm/) print "match" }', "match"),

        U("Strings"),
        T("length", "Characters in a string.",
          'BEGIN { print length("pycmd") }', "5"),
        T("substr", "From a position, counting from 1, for a length.",
          'BEGIN { print substr("pycmd", 3, 3) }', "cmd"),
        T("index", "Where one string appears in another; 0 if not at all.",
          'BEGIN { print index("pycmd", "c") }', "3"),
        T("toupper", "Upper case.",
          'BEGIN { print toupper("pycmd") }', "PYCMD"),
        T("split", "Breaks a string into an array; returns how many.",
          'BEGIN {\n    n = split("a,b,c", parts, ",")\n    print n, parts[2]\n}', "3 b"),
        T("sub", "Replaces the first match.",
          'BEGIN { s = "banana"; sub(/a/, "o", s); print s }', "bonana"),
        T("gsub", "Replaces every match, and says how many.",
          'BEGIN { s = "banana"; n = gsub(/a/, "o", s); print s, n }', "bonono 3"),
        T("match", "Finds a regex and sets RSTART and RLENGTH.",
          'BEGIN { match("abc123", /[0-9]+/); print RSTART, RLENGTH }', "4 3"),
        T("sprintf", "Formats into a string instead of printing.",
          'BEGIN { s = sprintf("%03d", 7); print s }', "007"),

        U("Arrays"),
        T("Associative arrays", "Indexed by strings.",
          'BEGIN { age["ada"] = 36; print age["ada"] }', "36"),
        T("in", "Is that key there?",
          'BEGIN { a["x"] = 1; print ("x" in a), ("y" in a) }', "1 0"),
        T("Looping over keys", "`for (k in a)`. The order is not promised.",
          'BEGIN {\n    a["k"] = 5\n    for (k in a) print k, a[k]\n}', "k 5"),
        T("delete", "Removes a key.",
          'BEGIN { a["x"] = 1; delete a["x"]; print length(a) }', "0"),
        T("Counting", "The most common AWK idiom.",
          'BEGIN {\n    n = split("a b a c a", w, " ")\n    for (i = 1; i <= n; i++) c[w[i]]++\n'
          '    print c["a"]\n}', "3"),
        T("Multi-dimensional keys", "A comma joins them with SUBSEP.",
          "BEGIN { grid[1, 2] = \"x\"; print grid[1, 2] }", "x"),

        U("Functions and records"),
        T("Functions", "Declared with `function`.",
          "function square(x) { return x * x }\nBEGIN { print square(9) }", "81"),
        T("Local variables", "Extra parameters act as locals.",
          "function total(n,    i, s) {\n    for (i = 1; i <= n; i++) s += i\n"
          "    return s\n}\nBEGIN { print total(10) }", "55"),
        T("Recursion", "Functions can call themselves.",
          "function fact(n) { return n <= 1 ? 1 : n * fact(n - 1) }\n"
          "BEGIN { print fact(5) }", "120"),
        T("Fields", "$1, $2... are the words of the current line.",
          'BEGIN {\n    $0 = "alpha beta gamma"\n    print $2, NF\n}', "beta 3"),
        T("The last field", "`$NF` is the last one.",
          'BEGIN { $0 = "a b c"; print $NF }', "c"),
        T("Changing a field", "Rebuilds the line with OFS between fields.",
          'BEGIN {\n    $0 = "a b c"\n    OFS = "-"\n    $2 = "B"\n    print\n}', "a-B-c"),
        T("FS", "Sets what separates fields.",
          'BEGIN {\n    FS = ","\n    $0 = "x,y,z"\n    print $3\n}', "z"),
        T("Math functions", "sqrt, sin, exp, log...",
          "BEGIN { print sqrt(144) }", "12"),
    ],
)

PROLOG = Course(
    "prolog", "Prolog", "Programming in logic: state facts and rules, ask questions.",
    ".pro", "text",
    [
        U("First steps", "A program runs main/0 here."),
        T("writeln", "Prints a term and a newline.",
          "main :- writeln(hello).", "hello"),
        T("format", "`~w` is a value, `~n` a newline.",
          "main :- format(\"~w and ~w~n\", [1, 2]).", "1 and 2"),
        T("Arithmetic needs is", "`X is Expr` works the expression out.",
          "main :- X is 7 * 6, writeln(X).", "42"),
        T("Division", "`/` may give a float; `//` is whole-number.",
          "main :-\n    X is 7 // 2, Y is 7 mod 2,\n    format(\"~w ~w~n\", [X, Y]).", "3 1"),
        T("Atoms and strings", "Lowercase names are atoms.",
          "main :- X = pycmd, writeln(X).", "pycmd"),
        T("Variables start with a capital", "And are bound once.",
          "main :- Name = ada, format(\"hi ~w~n\", [Name]).", "hi ada"),
        T("Commas mean and", "Each goal must succeed in turn.",
          "main :- X = 2, Y is X + 3, writeln(Y).", "5"),
        T("Comments", "`%` to the end of the line.",
          "% a note\nmain :- writeln(ok).", "ok"),

        U("Facts and rules"),
        T("Facts", "Things that are true.",
          "likes(ada, tea).\n\nmain :- ( likes(ada, tea) -> writeln(yes) ; writeln(no) ).",
          "yes"),
        T("Queries with variables", "Prolog finds a value that makes it true.",
          "parent(tom, bob).\n\nmain :- parent(tom, X), writeln(X).", "bob"),
        T("Rules", "`Head :- Body.` - the head is true if the body is.",
          "parent(tom, bob).\nparent(bob, ann).\n"
          "grand(X, Z) :- parent(X, Y), parent(Y, Z).\n\n"
          "main :- grand(tom, Who), writeln(Who).", "ann"),
        T("Several answers", "`findall` collects every solution.",
          "c(red).\nc(green).\nc(blue).\n\nmain :- findall(X, c(X), L), writeln(L).",
          "[red,green,blue]"),
        T("forall", "Do something for every solution.",
          "n(1).\nn(2).\nn(3).\n\nmain :- forall(n(X), write(X)), nl.", "123"),
        T("Negation", "`\\+` succeeds when the goal cannot be proved.",
          "bird(tweety).\n\nmain :- ( \\+ bird(rex) -> writeln(not_a_bird) ; true ).",
          "not_a_bird"),
        T("If-then-else", "`( Cond -> Then ; Else )`.",
          "main :-\n    X = 4,\n    ( X mod 2 =:= 0 -> writeln(even) ; writeln(odd) ).", "even"),
        T("Comparing numbers", "`=:=`, `<`, `>=` and friends evaluate both sides.",
          "main :-\n    ( 2 + 2 =:= 4 -> writeln(equal) ; writeln(differ) ).", "equal"),

        U("Unification"),
        T("= unifies", "Makes two terms the same if it can.",
          "main :-\n    point(X, 2) = point(1, Y),\n    format(\"~w ~w~n\", [X, Y]).", "1 2"),
        T("Structures", "Compound terms hold data.",
          "main :- P = person(ada, 36), P = person(N, _), writeln(N).", "ada"),
        T("== does not bind", "`==` asks if they are already identical.",
          "main :- ( a == a -> writeln(same) ; writeln(different) ).", "same"),

        U("Lists"),
        T("Lists", "Square brackets.",
          "main :- L = [1, 2, 3], writeln(L).", "[1,2,3]"),
        T("Head and tail", "`[H|T]` splits a list.",
          "main :- [H|T] = [1, 2, 3], writeln(H), writeln(T).", "1\n[2,3]"),
        T("length", "Relates a list to its length.",
          "main :- length([a, b, c], N), writeln(N).", "3"),
        T("member", "Is X in the list?",
          "main :-\n    ( member(2, [1, 2, 3])\n    -> writeln(yes)\n    ; writeln(no)\n    ).", "yes"),
        T("append", "Joins lists - or splits them, run backwards.",
          "main :- append([1], [2, 3], L), writeln(L).", "[1,2,3]"),
        T("append, backwards", "Ask what goes in front of [3].",
          "main :- append(X, [3], [1, 2, 3]), writeln(X).", "[1,2]"),
        T("reverse", "Back to front.",
          "main :- reverse([1, 2, 3], R), writeln(R).", "[3,2,1]"),
        T("nth0 and nth1", "Indexing from zero, or from one.",
          "main :- nth0(1, [a, b, c], X), writeln(X).", "b"),
        T("sum_list and max_list", "Summaries of a list of numbers.",
          "main :- sum_list([1, 2, 3], S), max_list([4, 9, 2], M),\n"
          "    format(\"~w ~w~n\", [S, M]).", "6 9"),
        T("msort", "Sorts, keeping duplicates.",
          "main :- msort([3, 1, 2, 1], L), writeln(L).", "[1,1,2,3]"),
        T("sort/2 removes duplicates", "And sorts what is left.",
          "main :- sort([3, 1, 2, 1], L), writeln(L).", "[1,2,3]"),
        T("numlist", "A list of the numbers in a range.",
          "main :- numlist(1, 5, L), writeln(L).", "[1,2,3,4,5]"),
        T("maplist", "Applies a goal across a list.",
          "double(X, Y) :- Y is X * 2.\n\nmain :- maplist(double, [1, 2, 3], L), writeln(L).",
          "[2,4,6]"),
        T("include", "Keeps elements for which a goal succeeds.",
          "big(X) :- X > 2.\n\nmain :- include(big, [1, 3, 5], L), writeln(L).", "[3,5]"),
        T("foldl", "Folds a list with a goal.",
          "add(X, A0, A) :- A is A0 + X.\n\nmain :- foldl(add, [1, 2, 3], 0, S), writeln(S).",
          "6"),

        U("Recursion"),
        T("Recursive rules", "A base case and a step.",
          "fact(0, 1) :- !.\nfact(N, F) :- N1 is N - 1, fact(N1, F1), F is N * F1.\n\n"
          "main :- fact(5, F), writeln(F).", "120"),
        T("Recursion on lists", "Empty list, or head plus the rest.",
          "total([], 0).\ntotal([H|T], S) :- total(T, S0), S is S0 + H.\n\n"
          "main :- total([1, 2, 3, 4], S), writeln(S).", "10"),
        T("The cut", "`!` commits to this clause: no going back for others.",
          "size(N, small) :- N < 10, !.\nsize(_, big).\n\n"
          "main :- size(5, S), writeln(S).", "small"),
        T("between", "Generates numbers in a range.",
          "main :- findall(X, between(1, 4, X), L), writeln(L).", "[1,2,3,4]"),
        T("Atoms to text", "`atom_length`, `atom_concat`, `upcase_atom`.",
          "main :- upcase_atom(pycmd, U), writeln(U).", "PYCMD"),
        T("atomic_list_concat", "Joins with a separator.",
          "main :- atomic_list_concat([a, b, c], '-', A), writeln(A).", "a-b-c"),
    ],
)

