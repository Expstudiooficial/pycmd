"""Scala and Groovy: the JVM's two best-known languages after Java and Kotlin."""

from pycmd_teach import Course, T, U


def _main(body: str) -> str:
    """Wraps statements in the object Scala 2 and Scala 3 both run."""
    inner = "\n".join("    " + line if line else "" for line in body.split("\n"))
    return "object Main {\n  def main(args: Array[String]): Unit = {\n" + "\n".join(
        "  " + line if line else "" for line in inner.split("\n")) + "\n  }\n}"


def _with(defs: str, body: str) -> str:
    """Definitions inside the object, then main."""
    head = "\n".join("  " + line if line else "" for line in defs.split("\n"))
    inner = "\n".join("      " + line if line else "" for line in body.split("\n"))
    return ("object Main {\n" + head + "\n\n  def main(args: Array[String]): Unit = {\n"
            + inner + "\n  }\n}")


