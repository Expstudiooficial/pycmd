FSHARP = Course(
    "fsharp", "F#", ".NET's functional language. Scripts run with dotnet fsi.",
    ".fsx", "text",
    [
        U("First steps"),
        T("printfn", "Prints with a format, then a newline.",
          'printfn "hello"', "hello"),
        T("Format holes", "`%d` for ints, `%s` for strings.",
          'printfn "%d %s" 7 "up"', "7 up"),
        T("%A", "Prints any value the way F# writes it.",
          "printfn \"%A\" [1; 2; 3]", "[1; 2; 3]"),
        T("let", "A name for a value. It does not change.",
          'let n = 5\nprintfn "%d" (n * n)', "25"),
        T("Arithmetic", "Ints divide into ints.",
          'printfn "%d %d" (7 / 2) (7 % 2)', "3 1"),
        T("Floats", "Write the point; ints and floats do not mix.",
          'printfn "%.1f" (7.0 / 2.0)', "3.5"),
        T("Converting", "`float` and `int` are functions.",
          'printfn "%.1f" (float 3 + 0.5)', "3.5"),
        T("Interpolation", "`$\"...{x}...\"`.",
          'let who = "Ada"\nprintfn $"hi {who}"', "hi Ada"),
        T("Comments", "`//` for a line.",
          '// a note\nprintfn "ok"', "ok"),

        U("Functions"),
        T("A function", "Parameters after the name, separated by spaces.",
          'let double x = x * 2\nprintfn "%d" (double 21)', "42"),
        T("Two parameters", "Applied with spaces too.",
          'let add a b = a + b\nprintfn "%d" (add 2 3)', "5"),
        T("fun", "A function with no name.",
          'printfn "%d" ((fun x -> x + 1) 41)', "42"),
        T("Partial application", "Fewer arguments gives a function back.",
          'let add a b = a + b\nlet inc = add 1\nprintfn "%d" (inc 9)', "10"),
        T("The pipe", "`x |> f` is `f x`, read left to right.",
          '5 |> (fun x -> x * 3) |> printfn "%d"', "15"),
        T("Composition", "`f >> g` runs f, then g.",
          'let inc x = x + 1\nlet dbl x = x * 2\nprintfn "%d" ((inc >> dbl) 4)', "10"),
        T("rec", "A function that calls itself says so.",
          'let rec fact n = if n = 0 then 1 else n * fact (n - 1)\nprintfn "%d" (fact 5)',
          "120"),
        T("Type annotations", "Optional, after a colon.",
          'let square (x: int) : int = x * x\nprintfn "%d" (square 9)', "81"),

        U("Decisions"),
        T("if then else", "An expression: both branches give a value.",
          'printfn "%s" (if 3 > 2 then "yes" else "no")', "yes"),
        T("Equality", "`=` compares; `<>` is not-equal.",
          'printfn "%b" (3 <> 4)', "true"),
        T("match", "Patterns, tried in order.",
          'let name n =\n    match n with\n    | 1 -> "one"\n    | _ -> "many"\n'
          'printfn "%s" (name 2)', "many"),
        T("Guards", "`when` adds a condition to a pattern.",
          'let sign n =\n    match n with\n    | n when n < 0 -> "neg"\n'
          '    | 0 -> "zero"\n    | _ -> "pos"\nprintfn "%s" (sign 4)', "pos"),

        U("Lists and sequences"),
        T("Lists", "Semicolons between elements.",
          'let xs = [1; 2; 3]\nprintfn "%d" xs.Length', "3"),
        T("Ranges", "`[1..5]` counts for you.",
          'printfn "%A" [1..5]', "[1; 2; 3; 4; 5]"),
        T("Cons", "`::` puts an element on the front.",
          'printfn "%A" (0 :: [1; 2])', "[0; 1; 2]"),
        T("List.map", "A function over every element.",
          'printfn "%A" (List.map (fun x -> x * 10) [1; 2; 3])', "[10; 20; 30]"),
        T("List.filter", "Keeps what passes.",
          '[1..6] |> List.filter (fun x -> x % 2 = 0) |> printfn "%A"', "[2; 4; 6]"),
        T("List.sum", "Adds them up.",
          'printfn "%d" (List.sum [1..10])', "55"),
        T("List.fold", "Combines them with a starting value.",
          'printfn "%d" (List.fold (fun acc x -> acc * x) 1 [1..5])', "120"),
        T("Matching a list", "Empty, or head and tail.",
          "let rec total xs =\n    match xs with\n    | [] -> 0\n"
          '    | x :: rest -> x + total rest\nprintfn "%d" (total [1; 2; 3])', "6"),
        T("Comprehensions", "`[ for x in ... -> ... ]`.",
          'printfn "%A" [ for x in 1..4 -> x * x ]', "[1; 4; 9; 16]"),
        T("Arrays", "`[| |]`, fixed size, mutable.",
          'let a = [| 1; 2; 3 |]\na.[0] <- 9\nprintfn "%d" a.[0]', "9"),
        T("Seq", "Lazy: only as much as you ask for.",
          'Seq.initInfinite (fun i -> i * 2)\n|> Seq.take 4\n|> Seq.toList\n|> printfn "%A"',
          "[0; 2; 4; 6]"),
        T("List.sortBy", "Sorts by a key.",
          '["ccc"; "a"; "bb"]\n|> List.sortBy String.length\n|> printfn "%A"',
          '["a"; "bb"; "ccc"]'),

        U("Types"),
        T("Tuples", "Commas make one; `fst` and `snd` take a pair apart.",
          'let p = (1, "a")\nprintfn "%d %s" (fst p) (snd p)', "1 a"),
        T("Records", "Named fields.",
          'type P = { Name: string; Age: int }\nlet ada = { Name = "Ada"; Age = 36 }\n'
          'printfn "%s" ada.Name', "Ada"),
        T("Copy and update", "`with` changes some fields of a copy.",
          'type P = { Name: string; Age: int }\nlet a = { Name = "Ada"; Age = 36 }\n'
          'printfn "%d" { a with Age = 37 }.Age', "37"),
        T("Unions", "A type that is one of several cases.",
          "type Shape =\n    | Circle of float\n    | Square of float\n"
          "let area s =\n    match s with\n    | Circle r -> 3.0 * r * r\n"
          '    | Square x -> x * x\nprintfn "%.1f" (area (Square 3.0))', "9.0"),
        T("Option", "Some value, or None.",
          'let show o =\n    match o with\n    | Some n -> string n\n    | None -> "none"\n'
          'printfn "%s" (show None)', "none"),
        T("List.tryFind", "Searching returns an option.",
          '[1; 3; 5] |> List.tryFind (fun x -> x > 2) |> printfn "%A"', "Some 3"),
        T("Result", "Ok or Error.",
          'let safeDiv a b =\n    if b = 0 then Error "div by zero"\n    else Ok (a / b)\n'
          'printfn "%A" (safeDiv 10 2)', "Ok 5"),

        U("Mutation and .NET"),
        T("mutable", "Ask for it, and use `<-` to change it.",
          'let mutable n = 1\nn <- n + 4\nprintfn "%d" n', "5"),
        T("for loops", "`for i in a .. b do`.",
          'for i in 1..3 do\n    printf "%d " i\nprintfn ""', "1 2 3"),
        T("while", "Loops while the test holds.",
          'let mutable i = 3\nwhile i > 0 do\n    printf "%d" i\n    i <- i - 1\n'
          'printfn ""', "321"),
        T("Strings", "The .NET string methods are all there.",
          'printfn "%s" ("pycmd".ToUpper())', "PYCMD"),
        T("String.concat", "Joins with a separator.",
          'printfn "%s" (String.concat "-" ["a"; "b"; "c"])', "a-b-c"),
        T("Map", "An immutable dictionary.",
          'let m = Map.ofList [("a", 1); ("b", 2)]\nprintfn "%d" m.["b"]', "2"),
        T("try with", "Catches an exception.",
          'try\n    failwith "boom"\nwith ex ->\n    printfn "caught %s" ex.Message',
          "caught boom"),
    ],
)

