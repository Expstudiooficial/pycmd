        T("foreach", "Every element of a collection, in order.",
          'foreach (var c in "abc")\n{\n    Console.Write(c);\n}\nConsole.WriteLine();',
          "abc"),
        T("break and continue", "Leave the loop, or skip to the next round.",
          "for (int i = 0; i < 10; i++)\n{\n    if (i == 1) continue;\n"
          "    if (i == 4) break;\n    Console.Write(i);\n}\nConsole.WriteLine();", "023"),

        U("Collections"),
        T("Arrays", "Fixed size, indexed from zero.",
          "int[] xs = { 10, 20, 30 };\nConsole.WriteLine(xs[2]);", "30"),
        T("List", "A growable array.",
          "var xs = new List<int> { 1, 2 };\nxs.Add(3);\nConsole.WriteLine(xs.Count);", "3"),
