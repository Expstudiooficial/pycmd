"""Elixir and Erlang, on the BEAM - the VM built for systems that never stop."""

from pycmd_teach import Course, T, U

ELIXIR = Course(
    "elixir", "Elixir", "Friendly syntax on Erlang's VM. Pipes, patterns, processes.",
    ".exs", "text",
    [
        U("First steps"),
        T("IO.puts", "Prints a line.",
          'IO.puts("hello")', "hello"),
        T("Brackets are optional", "For a call on its own line.",
          'IO.puts "hello"', "hello"),
        T("Arithmetic", "`/` always gives a float; `div` and `rem` do not.",
          "IO.puts(7 / 2)\nIO.puts(div(7, 2))\nIO.puts(rem(7, 2))", "3.5\n3\n1"),
        T("Names", "A name is bound to a value; rebinding makes a new binding.",
          "n = 5\nIO.puts(n * n)", "25"),
        T("Interpolation", "`#{}` inside double quotes.",
          'name = "Ada"\nIO.puts("hi #{name}")', "hi Ada"),
        T("Joining strings", "`<>` concatenates.",
          'IO.puts("py" <> "cmd")', "pycmd"),
        T("IO.inspect", "Prints any value the way Elixir writes it.",
          "IO.inspect([1, 2, 3])", "[1, 2, 3]"),
        T("Atoms", "Constants whose name is their value.",
          "IO.inspect(:ok)", ":ok"),
        T("Comments", "`#` to the end of the line.",
          '# a note\nIO.puts("ok")', "ok"),

        U("Functions and pipes"),
        T("Anonymous functions", "`fn ... end`, called with a dot.",
          "double = fn x -> x * 2 end\nIO.puts(double.(21))", "42"),
        T("The capture shorthand", "`&(&1 + 1)` is a short fn.",
          "inc = &(&1 + 1)\nIO.puts(inc.(41))", "42"),
        T("Modules", "Named functions live in modules.",
          "defmodule M do\n  def square(x), do: x * x\nend\n\nIO.puts(M.square(9))", "81"),
        T("Multi-clause functions", "Clauses are matched top to bottom.",
          'defmodule M do\n  def name(1), do: "one"\n  def name(_), do: "many"\nend\n\n'
          "IO.puts(M.name(1))", "one"),
        T("Guards", "`when` adds a condition to a clause.",
          'defmodule M do\n  def sign(n) when n < 0, do: "neg"\n  def sign(0), do: "zero"\n'
          '  def sign(_), do: "pos"\nend\n\nIO.puts(M.sign(-3))', "neg"),
        T("Recursion", "The way to loop.",
          "defmodule M do\n  def fact(0), do: 1\n  def fact(n), do: n * fact(n - 1)\nend\n\n"
          "IO.puts(M.fact(5))", "120"),
        T("Default arguments", "`\\\\` gives a default.",
          'defmodule M do\n  def hi(who \\\\ "you"), do: "hi #{who}"\nend\n\nIO.puts(M.hi())',
          "hi you"),
        T("The pipe", "`x |> f(y)` is `f(x, y)`.",
          '"pycmd" |> String.upcase() |> IO.puts()', "PYCMD"),
        T("Longer pipelines", "Each step feeds the next.",
          "1..5 |> Enum.map(&(&1 * &1)) |> Enum.sum() |> IO.puts()", "55"),

        U("Decisions"),
        T("if", "An expression; `else` is optional.",
          'IO.puts(if 3 > 2, do: "yes", else: "no")', "yes"),
        T("case", "Matches a value against patterns.",
          'result = case {:ok, 5} do\n  {:ok, n} -> n * 2\n  {:error, _} -> 0\nend\n'
          "IO.puts(result)", "10"),
        T("cond", "The first true condition wins.",
          'n = 15\nIO.puts(cond do\n  rem(n, 15) == 0 -> "fizzbuzz"\n  true -> n\nend)',
          "fizzbuzz"),
        T("Truthiness", "Only `nil` and `false` are false.",
          'IO.puts(if 0, do: "true", else: "false")', "true"),
        T("Strict equality", "`===` also checks the type: 1 and 1.0 differ.",
          "IO.inspect(1 == 1.0)\nIO.inspect(1 === 1.0)", "true\nfalse"),

        U("Pattern matching"),
        T("= is a match", "The left side is a pattern.",
          "{a, b} = {1, 2}\nIO.puts(a + b)", "3"),
        T("Lists head and tail", "`[h | t]` splits a list.",
          "[h | t] = [1, 2, 3]\nIO.inspect(h)\nIO.inspect(t)", "1\n[2, 3]"),
        T("The pin operator", "`^x` matches against x's value instead of rebinding.",
          'x = 1\ncase 1 do\n  ^x -> IO.puts("same")\n  _ -> IO.puts("different")\nend',
          "same"),
        T("Ignoring with _", "Match it, keep nothing.",
          "{_, second} = {:skip, :keep}\nIO.inspect(second)", ":keep"),
        T("Matching maps", "Only the keys you name have to be there.",
          '%{name: n} = %{name: "Ada", age: 36}\nIO.puts(n)', "Ada"),

        U("Collections"),
        T("Lists", "Linked lists. `++` joins them.",
          "IO.inspect([1, 2] ++ [3])", "[1, 2, 3]"),
        T("length", "Walks the list to count it.",
          "IO.puts(length([1, 2, 3]))", "3"),
        T("Tuples", "Fixed size, quick to index.",
          "t = {:a, :b, :c}\nIO.inspect(elem(t, 1))", ":b"),
        T("Maps", "Key-value pairs.",
          'ages = %{"ada" => 36}\nIO.puts(ages["ada"])', "36"),
        T("Atom keys", "Read with a dot.",
          "p = %{x: 3, y: 4}\nIO.puts(p.x * p.y)", "12"),
        T("Updating a map", "`%{m | k: v}` for a key that exists.",
          "p = %{x: 1}\np2 = %{p | x: 9}\nIO.puts(p2.x)", "9"),
        T("Map.put", "Adds or replaces a key.",
          "IO.inspect(Map.put(%{}, :k, 1))", "%{k: 1}"),
        T("Keyword lists", "A list of atom pairs, often used for options.",
          "opts = [size: 2, color: :red]\nIO.inspect(opts[:color])", ":red"),
        T("Ranges", "`1..5`, enumerable.",
          "IO.inspect(Enum.to_list(1..4))", "[1, 2, 3, 4]"),

        U("Enum"),
        T("Enum.map", "A function over every element.",
          "IO.inspect(Enum.map([1, 2, 3], fn x -> x * 10 end))", "[10, 20, 30]"),
        T("Enum.filter", "Keeps what passes.",
          "IO.inspect(Enum.filter(1..6, &(rem(&1, 2) == 0)))", "[2, 4, 6]"),
        T("Enum.reduce", "Folds to one value.",
          "add = fn x, acc -> x + acc end\n"
          "IO.puts(Enum.reduce([1, 2, 3, 4], 0, add))", "10"),
        T("Enum.sort", "Sorted, ascending by default.",
          "IO.inspect(Enum.sort([3, 1, 2]))", "[1, 2, 3]"),
        T("Enum.join", "Into one string.",
          'IO.puts(Enum.join(["a", "b", "c"], "-"))', "a-b-c"),
        T("Comprehensions", "`for x <- list, do: ...`.",
          "IO.inspect(for x <- 1..4, do: x * x)", "[1, 4, 9, 16]"),
        T("Filters in for", "Conditions after the generator.",
          "IO.inspect(for x <- 1..10, rem(x, 3) == 0, do: x)", "[3, 6, 9]"),
        T("Enum.with_index", "Pairs each element with its position.",
          'IO.inspect(Enum.with_index(["a", "b"]))', '[{"a", 0}, {"b", 1}]'),
        T("Enum.frequencies", "Counts each value.",
          'IO.inspect(Enum.frequencies(["a", "b", "a"]))', '%{"a" => 2, "b" => 1}'),

        U("Strings and errors"),
        T("String functions", "In the String module.",
          'IO.puts(String.length("pycmd"))', "5"),
        T("String.split", "Breaks text into a list.",
          'IO.inspect(String.split("a,b", ","))', '["a", "b"]'),
        T("Charlists", "Single quotes are a list of codepoints.",
          "IO.inspect(Enum.sum(~c\"ab\"))", "195"),
        T("Ok tuples", "Functions say how it went: {:ok, v} or {:error, why}.",
          'IO.inspect(Integer.parse("41"))', '{41, ""}'),
        T("with", "Chains matches; stops at the first that fails.",
          "r = with {:ok, a} <- {:ok, 1},\n       {:ok, b} <- {:ok, 2} do\n  a + b\nend\n"
          "IO.puts(r)", "3"),
        T("raise and rescue", "Exceptions exist, for the truly exceptional.",
          'try do\n  raise "boom"\nrescue\n  e -> IO.puts("caught #{e.message}")\nend',
          "caught boom"),

        U("Processes"),
        T("spawn and send", "A process is cheap; messages are how they talk.",
          "parent = self()\nspawn(fn -> send(parent, {:hi, 42}) end)\n"
          "receive do\n  {:hi, n} -> IO.puts(n)\nend", "42"),
        T("Tasks", "Run something concurrently and await its answer.",
          "t = Task.async(fn -> 6 * 7 end)\nIO.puts(Task.await(t))", "42"),
        T("Agents", "State that lives in a process.",
          "{:ok, a} = Agent.start_link(fn -> 0 end)\nAgent.update(a, &(&1 + 5))\n"
          "IO.puts(Agent.get(a, & &1))", "5"),
    ],
)

ERLANG = Course(
    "erlang", "Erlang", "The language telephone switches were written in. Run as escript.",
    ".erl", "text",
    [
        U("First steps", "An escript runs main/1."),
        T("main", "An escript starts at `main(_)`.",
          'main(_) ->\n    io:format("hello~n").', "hello"),
        T("~n and ~p", "`~n` is a newline; `~p` prints any term.",
          'main(_) ->\n    io:format("~p~n", [[1, 2, 3]]).', "[1,2,3]"),
        T("Arithmetic", "`/` gives a float; `div` and `rem` do not.",
          'main(_) ->\n    io:format("~p ~p ~p~n", [7 div 2, 7 rem 2, 7 / 2]).',
          "3 1 3.5"),
        T("Variables start with a capital", "And can be bound only once.",
          'main(_) ->\n    N = 5,\n    io:format("~p~n", [N * N]).', "25"),
        T("Commas and full stops", "`,` separates expressions; `.` ends a function.",
          'main(_) ->\n    A = 1,\n    B = 2,\n    io:format("~p~n", [A + B]).', "3"),
        T("Atoms", "Lowercase names are constants.",
          'main(_) ->\n    io:format("~p~n", [ok]).', "ok"),
        T("~s", "Prints a string without quotes.",
          'main(_) ->\n    io:format("~s~n", ["pycmd"]).', "pycmd"),
        T("Comments", "`%` to the end of the line.",
          '%% a note\nmain(_) ->\n    io:format("ok~n").', "ok"),

        U("Functions"),
        T("Your own function", "Defined beside main, in the same file.",
          'double(X) -> X * 2.\n\nmain(_) ->\n    io:format("~p~n", [double(21)]).', "42"),
        T("Clauses", "Separated by `;`, matched top to bottom.",
          'name(1) -> one;\nname(_) -> many.\n\nmain(_) ->\n    io:format("~p~n", [name(1)]).',
          "one"),
        T("Guards", "`when` adds a condition.",
          "sign(N) when N < 0 -> neg;\nsign(0) -> zero;\nsign(_) -> pos.\n\n"
          'main(_) ->\n    io:format("~p~n", [sign(-1)]).', "neg"),
        T("Recursion", "How Erlang loops.",
          "fact(0) -> 1;\nfact(N) -> N * fact(N - 1).\n\n"
          'main(_) ->\n    io:format("~p~n", [fact(5)]).', "120"),
        T("Tail recursion", "An accumulator keeps the stack flat.",
          "sum([], Acc) -> Acc;\nsum([H | T], Acc) -> sum(T, Acc + H).\n\n"
          'main(_) ->\n    io:format("~p~n", [sum([1, 2, 3], 0)]).', "6"),
        T("Anonymous functions", "`fun(X) -> ... end`.",
          'main(_) ->\n    F = fun(X) -> X + 1 end,\n    io:format("~p~n", [F(41)]).', "42"),

        U("Decisions"),
        T("case", "Pattern match on a value.",
          "main(_) ->\n    R = case {ok, 5} of\n        {ok, N} -> N * 2;\n"
          '        {error, _} -> 0\n    end,\n    io:format("~p~n", [R]).', "10"),
        T("if", "Guards in a row; one must be true.",
          "main(_) ->\n    N = 4,\n    R = if\n        N rem 2 =:= 0 -> even;\n"
          '        true -> odd\n    end,\n    io:format("~p~n", [R]).', "even"),
        T("Exact equality", "`=:=` checks type too; `==` does not.",
          'main(_) ->\n    io:format("~p ~p~n", [1 == 1.0, 1 =:= 1.0]).', "true false"),
        T("Booleans are atoms", "`true` and `false`, combined with andalso.",
          'main(_) ->\n    io:format("~p~n", [true andalso not false]).', "true"),

        U("Data"),
        T("Tuples", "Fixed size, curly braces.",
          'main(_) ->\n    {A, B} = {1, 2},\n    io:format("~p~n", [A + B]).', "3"),
        T("element", "Index a tuple, from one.",
          'main(_) ->\n    io:format("~p~n", [element(2, {a, b, c})]).', "b"),
        T("Lists", "Head and tail with `|`.",
          'main(_) ->\n    [H | T] = [1, 2, 3],\n    io:format("~p ~p~n", [H, T]).', "1 [2,3]"),
        T("++", "Joins lists.",
          'main(_) ->\n    io:format("~p~n", [[1] ++ [2, 3]]).', "[1,2,3]"),
        T("length", "How many elements.",
          'main(_) ->\n    io:format("~p~n", [length([a, b, c])]).', "3"),
        T("Strings are lists", "Of character codes.",
          'main(_) ->\n    io:format("~p~n", [length("pycmd")]).', "5"),
        T("Maps", "`#{key => value}`.",
          'main(_) ->\n    M = #{a => 1, b => 2},\n    io:format("~p~n", [maps:get(b, M)]).',
          "2"),
        T("Updating a map", "`M#{k => v}` makes a new map.",
          'main(_) ->\n    M = #{a => 1},\n    M2 = M#{a => 9},\n'
          '    io:format("~p~n", [maps:get(a, M2)]).', "9"),
        T("Records of data", "Tagged tuples are the everyday shape.",
          'main(_) ->\n    P = {person, "Ada", 36},\n    {person, Name, _} = P,\n'
          '    io:format("~s~n", [Name]).', "Ada"),

        U("The lists module"),
        T("lists:map", "A function over every element.",
          'main(_) ->\n    L = lists:map(fun(X) -> X * 10 end, [1, 2, 3]),\n'
          '    io:format("~p~n", [L]).', "[10,20,30]"),
        T("lists:filter", "Keeps what passes.",
          'main(_) ->\n    Even = fun(X) -> X rem 2 =:= 0 end,\n'
          '    L = lists:filter(Even, [1, 2, 3, 4]),\n'
          '    io:format("~p~n", [L]).', "[2,4]"),
        T("lists:foldl", "Folds from the left.",
          'main(_) ->\n    S = lists:foldl(fun(X, A) -> X + A end, 0, [1, 2, 3]),\n'
          '    io:format("~p~n", [S]).', "6"),
        T("lists:seq", "Counts from one number to another.",
          'main(_) ->\n    io:format("~p~n", [lists:seq(1, 5)]).', "[1,2,3,4,5]"),
        T("lists:sum and max", "The summaries you expect.",
          'main(_) ->\n    S = lists:sum([1, 2, 3]),\n    M = lists:max([4, 9, 2]),\n'
          '    io:format("~p ~p~n", [S, M]).',
          "6 9"),
        T("lists:sort", "Sorted ascending.",
          'main(_) ->\n    io:format("~p~n", [lists:sort([3, 1, 2])]).', "[1,2,3]"),
        T("lists:reverse", "Back to front.",
          'main(_) ->\n    io:format("~p~n", [lists:reverse([1, 2, 3])]).', "[3,2,1]"),
        T("List comprehensions", "`[Expr || X <- List]`.",
          'main(_) ->\n    io:format("~p~n", [[X * X || X <- [1, 2, 3]]]).', "[1,4,9]"),
        T("With a filter", "Conditions after the generator.",
          'main(_) ->\n    L = [X || X <- lists:seq(1, 10), X rem 3 =:= 0],\n'
          '    io:format("~p~n", [L]).', "[3,6,9]"),

        U("Processes"),
        T("spawn", "Starts a process running a function.",
          "main(_) ->\n    Me = self(),\n    spawn(fun() -> Me ! {hi, 42} end),\n"
          '    receive\n        {hi, N} -> io:format("~p~n", [N])\n    end.', "42"),
        T("receive with a timeout", "`after` fires when nothing arrives.",
          "main(_) ->\n    receive\n        _ -> ok\n    after 10 ->\n"
          '        io:format("nothing came~n")\n    end.', "nothing came"),
        T("A tiny server", "A process that loops, answering messages.",
          "loop(N) ->\n    receive\n        {add, X} -> loop(N + X);\n"
          "        {get, From} -> From ! N, loop(N)\n    end.\n\n"
          "main(_) ->\n    P = spawn(fun() -> loop(0) end),\n    P ! {add, 5},\n"
          '    P ! {get, self()},\n    receive V -> io:format("~p~n", [V]) end.', "5"),
        T("catch errors", "`try ... catch` handles them.",
          "main(_) ->\n    R = try 1 / 0\n        catch error:badarith -> caught\n    end,\n"
          '    io:format("~p~n", [R]).', "caught"),
    ],
)

